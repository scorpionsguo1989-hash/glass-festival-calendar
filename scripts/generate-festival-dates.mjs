import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { Solar, Lunar } from "lunar-javascript";

const target = new URL("../src/festival-dates.generated.js", import.meta.url);
const lunarDates = {
  lantern: [1, 15],
  dragonBoat: [5, 5],
  qixi: [7, 7],
  midAutumn: [8, 15],
  doubleNinth: [9, 9],
};
const festivalDates = {};

function add(id, solar, year) {
  const date = solar.toYmd();
  assert.equal(solar.getYear(), year, id + " " + date);
  (festivalDates[id] ??= []).push(date);
}

for (let year = 2026; year <= 2030; year++) {
  const newYear = Lunar.fromYmd(year, 1, 1).getSolar();
  add("eve", newYear.next(-1), year);
  add("spring", newYear, year);
  for (const [id, [month, day]] of Object.entries(lunarDates)) {
    add(id, Lunar.fromYmd(year, month, day).getSolar(), year);
  }
  const terms = Solar.fromYmd(year, 7, 1).getLunar().getJieQiTable();
  add("qingming", terms["清明"], year);
  // The table lists the preceding winter solstice as 冬至 and the next as DONG_ZHI.
  add("winterSolstice", terms.DONG_ZHI, year);
}

const lines = Object.entries(festivalDates).map(([id, dates]) => "  " + id + ": " + JSON.stringify(dates) + ",");
const content = [
  "// Generated by npm run generate:calendar with lunar-javascript (MIT).",
  "export const FESTIVAL_DATES = {",
  ...lines,
  "};",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  assert.equal(readFileSync(target, "utf8"), content, "Regenerate the date table with npm run generate:calendar.");
  console.log("Generated festival dates match the committed file.");
} else {
  writeFileSync(target, content);
}
